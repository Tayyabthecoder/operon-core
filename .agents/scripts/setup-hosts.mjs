import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { HOSTS, checkHostFiles, writeHostFiles } from './lib/host-adapters.mjs';

/**
 * Generates project files for Cursor, Gemini CLI, and Codex CLI from the framework sources.
 *
 *   node .agents/scripts/setup-hosts.mjs [--root <dir>] [--host cursor,gemini,codex]          write
 *   node .agents/scripts/setup-hosts.mjs [--root <dir>] [--host ...] --check                  exit 1 on drift
 *
 * Files the framework did not write are never overwritten or deleted.
 */

function main(argv) {
  const option = (name) => {
    const index = argv.indexOf(name);
    return index !== -1 ? argv[index + 1] : undefined;
  };
  const root = path.resolve(option('--root') || process.cwd());
  const hosts = option('--host') ? option('--host').split(',').map((h) => h.trim()).filter(Boolean) : [...HOSTS];

  if (argv.includes('--check')) {
    const { missing, changed, stale, conflicts } = checkHostFiles(root, hosts);
    const problems = [
      ...missing.map((f) => `missing: ${f}`), ...changed.map((f) => `changed: ${f}`),
      ...stale.map((f) => `stale: ${f}`), ...conflicts.map((f) => `conflict (not generated by the framework): ${f}`),
    ];
    if (problems.length) {
      process.stderr.write(`Host files are out of date (${problems.length}). Run: node .agents/scripts/setup-hosts.mjs\n${problems.slice(0, 20).join('\n')}\n`);
      return 1;
    }
    process.stdout.write(`Host files for ${hosts.join(', ')} match the framework sources.\n`);
    return 0;
  }
  const { written, removed, conflicts } = writeHostFiles(root, hosts);
  process.stdout.write(`Wrote ${written} files for ${hosts.join(', ')}${removed.length ? `, removed ${removed.length} stale` : ''}.\n`);
  for (const file of conflicts) process.stdout.write(`Skipped ${file}: it exists and was not generated by the framework.\n`);
  return conflicts.length ? 1 : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`setup-hosts: ${error.message}\n`);
    process.exitCode = 1;
  }
}
