import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Claude Code Setup
 *
 * Claude Code does not read `.agents/`. This script wires the framework into a
 * project's `.claude/` folder so Claude Code discovers the same skills, workflows,
 * rules, subagents, and hooks:
 *
 *   .claude/skills    -> .agents/skills      (junction on Windows, symlink elsewhere)
 *   .claude/commands  -> .agents/workflows
 *   .claude/rules     -> .agents/rules
 *   .claude/agents/   generated from .agents/agents/*.md with Claude Code tool and model names
 *   .claude/settings.json  copied from claude-code.settings.example.json when absent
 *   CLAUDE.md         created with `@AGENTS.md` when absent
 *
 * Existing files that this script did not create are never overwritten; the script
 * reports what to merge by hand instead.
 *
 * Usage:
 *   node .agents/scripts/adapters/setup-claude-code.mjs [--root <dir>] [--check]
 */

const GENERATED_MARKER = '<!-- Generated by .agents/scripts/adapters/setup-claude-code.mjs';

/** Framework (Antigravity) tool names -> Claude Code tool names. */
export const TOOL_MAP = {
  read_file: ['Read', 'Grep', 'Glob'],
  write_file: ['Write'],
  edit_file: ['Edit'],
  run_command: ['Bash'],
  send_message: [],
  manage_task: [],
};

/** Framework model tiers -> Claude Code model values (overridable in framework.config.json `claudeCode.modelMap`). */
export const DEFAULT_MODEL_MAP = { pro: 'inherit', flash: 'inherit' };

const LINKS = [
  { link: '.claude/skills', target: '.agents/skills' },
  { link: '.claude/commands', target: '.agents/workflows' },
  { link: '.claude/rules', target: '.agents/rules' },
];

/**
 * Converts a framework subagent definition into a Claude Code subagent file.
 * Keeps the body unchanged; rewrites frontmatter to name, description, tools,
 * model, and skills (skill names without the `skills/` prefix).
 * @param {string} source Framework agent Markdown
 * @param {string} sourceRel Source path for the generated-file marker
 * @param {Record<string,string>} modelMap
 * @returns {string}
 */
export function toClaudeAgent(source, sourceRel, modelMap = DEFAULT_MODEL_MAP) {
  const text = source.replace(/^﻿/, '');
  const fm = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!fm) throw new Error(`No frontmatter in ${sourceRel}`);
  const front = fm[1];
  const body = text.slice(fm[0].length);

  const scalar = (key) => {
    const m = front.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
    return m ? m[1].trim() : undefined;
  };
  const list = (key) => {
    const m = front.match(new RegExp(`^${key}:\\s*\\r?\\n((?:\\s+-\\s*.+\\r?\\n?)+)`, 'm'));
    return m ? [...m[1].matchAll(/-\s*(.+)/g)].map((x) => x[1].trim()) : [];
  };

  const name = scalar('name');
  const description = scalar('description');
  if (!name || !description) throw new Error(`Missing name or description in ${sourceRel}`);

  const tools = [];
  for (const tool of list('tools')) {
    if (!(tool in TOOL_MAP)) throw new Error(`Unmapped tool "${tool}" in ${sourceRel}`);
    for (const mapped of TOOL_MAP[tool]) if (!tools.includes(mapped)) tools.push(mapped);
  }
  const tier = scalar('model');
  const model = (tier && modelMap[tier]) || 'inherit';
  const skills = list('skills').map((s) => s.replace(/^skills\//, ''));

  const out = [
    '---',
    `name: ${name}`,
    `description: ${description}`,
    `tools: ${tools.join(', ')}`,
    `model: ${model}`,
  ];
  if (skills.length) out.push('skills:', ...skills.map((s) => `  - ${s}`));
  out.push('---', '', `${GENERATED_MARKER} from ${sourceRel}; edit the source, not this file. -->`, '', body.replace(/^\s+/, ''));
  return out.join('\n');
}

function readConfigModelMap(root) {
  try {
    const config = JSON.parse(fs.readFileSync(path.join(root, '.agents', 'framework.config.json'), 'utf8').replace(/^﻿/, ''));
    return { ...DEFAULT_MODEL_MAP, ...(config.claudeCode?.modelMap || {}) };
  } catch {
    return DEFAULT_MODEL_MAP;
  }
}

function linkPointsTo(linkPath, targetPath) {
  try {
    return fs.realpathSync.native(linkPath).toLowerCase() === fs.realpathSync.native(targetPath).toLowerCase();
  } catch {
    return false;
  }
}

/**
 * Wires (or, with check=true, inspects) Claude Code discovery for a framework root.
 * @param {string} root
 * @param {{ check?: boolean }} [options]
 * @returns {{ ok: boolean, actions: string[], problems: string[] }}
 */
export function setupClaudeCode(root, options = {}) {
  const check = options.check === true;
  const actions = [];
  const problems = [];
  const abs = (p) => path.join(root, p);

  if (!fs.existsSync(abs('.agents'))) {
    return { ok: false, actions, problems: [`No .agents/ folder under ${root}`] };
  }
  if (!check) fs.mkdirSync(abs('.claude'), { recursive: true });

  // 1. Directory links
  for (const { link, target } of LINKS) {
    const linkPath = abs(link);
    const targetPath = abs(target);
    if (linkPointsTo(linkPath, targetPath)) continue;
    let exists = false;
    try {
      fs.lstatSync(linkPath);
      exists = true;
    } catch {
      exists = false;
    }
    if (exists) {
      problems.push(`${link} exists but does not point to ${target}; move it aside and rerun.`);
    } else if (check) {
      problems.push(`${link} is missing (should point to ${target}).`);
    } else {
      if (process.platform === 'win32') fs.symlinkSync(targetPath, linkPath, 'junction');
      else fs.symlinkSync(path.relative(path.dirname(linkPath), targetPath), linkPath, 'dir');
      actions.push(`Linked ${link} -> ${target}`);
    }
  }

  // 2. Generated subagents
  const modelMap = readConfigModelMap(root);
  const agentsOut = abs('.claude/agents');
  const sources = fs.readdirSync(abs('.agents/agents')).filter((f) => f.endsWith('.md') && f !== 'README.md').sort();
  if (!check) fs.mkdirSync(agentsOut, { recursive: true });
  for (const file of sources) {
    const sourceRel = `.agents/agents/${file}`;
    const wanted = toClaudeAgent(fs.readFileSync(abs(sourceRel), 'utf8'), sourceRel, modelMap);
    const outPath = path.join(agentsOut, file);
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
    if (current === wanted) continue;
    if (current !== null && !current.includes(GENERATED_MARKER)) {
      problems.push(`.claude/agents/${file} was not generated by this script; leaving it unchanged.`);
    } else if (check) {
      problems.push(`.claude/agents/${file} is ${current === null ? 'missing' : 'out of date'}.`);
    } else {
      fs.writeFileSync(outPath, wanted, 'utf8');
      actions.push(`${current === null ? 'Generated' : 'Regenerated'} .claude/agents/${file}`);
    }
  }

  // 3. Hook settings
  const settingsPath = abs('.claude/settings.json');
  const examplePath = abs('.agents/scripts/adapters/claude-code.settings.example.json');
  if (!fs.existsSync(settingsPath)) {
    if (check) problems.push('.claude/settings.json is missing (adapter hooks not registered).');
    else {
      fs.copyFileSync(examplePath, settingsPath);
      actions.push('Created .claude/settings.json with the adapter hooks');
    }
  } else if (!fs.readFileSync(settingsPath, 'utf8').includes('adapters/claude-code.mjs')) {
    problems.push('.claude/settings.json exists without the adapter hooks; merge claude-code.settings.example.json into it by hand.');
  }

  // 4. CLAUDE.md
  const claudeMd = abs('CLAUDE.md');
  if (!fs.existsSync(claudeMd)) {
    if (check) problems.push('CLAUDE.md is missing (AGENTS.md is not imported).');
    else {
      fs.writeFileSync(claudeMd, '@AGENTS.md\n', 'utf8');
      actions.push('Created CLAUDE.md importing @AGENTS.md');
    }
  } else if (!/^@AGENTS\.md\s*$/m.test(fs.readFileSync(claudeMd, 'utf8'))) {
    problems.push('CLAUDE.md exists without an "@AGENTS.md" line; add it by hand.');
  }

  return { ok: problems.length === 0, actions, problems };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const rootArg = args.includes('--root') ? args[args.indexOf('--root') + 1] : process.cwd();
  const result = setupClaudeCode(path.resolve(rootArg), { check: args.includes('--check') });
  for (const a of result.actions) console.log(`  [DONE] ${a}`);
  for (const p of result.problems) console.log(`  [TODO] ${p}`);
  console.log(result.ok ? 'Claude Code wiring is complete.' : 'Claude Code wiring is incomplete.');
  process.exit(result.ok ? 0 : 1);
}
