import fs from 'node:fs';
import path from 'node:path';
import { claudeCodeRuleLoading, rulePaths } from './rule-metadata.mjs';

/**
 * Generates project files for hosts other than Claude Code from the framework sources.
 *
 *   cursor  .cursor/rules/*.mdc, .cursor/agents/*.md
 *   gemini  GEMINI.md, .gemini/agents/*.md, .gemini/commands/*.toml
 *   codex   .codex/agents/*.toml
 *
 * All three hosts read `.agents/skills` natively, and Codex and Cursor read `AGENTS.md`, so those
 * need nothing generated. What is NOT generated: hooks, command allowlists, and sandbox settings.
 * The allow/ask/deny enforcement lives in the Claude Code adapter; these files carry the rules,
 * roles, and workflows only.
 *
 * Formats come from each host's official documentation (checked 2026-11-12); none of the output
 * has been loaded by the host itself yet.
 */

export const HOSTS = Object.freeze(['cursor', 'gemini', 'codex']);
export const MARKER = 'Generated by .agents/scripts/setup-hosts.mjs';

const OWNED_DIRS = {
  cursor: [['.cursor/rules', '.mdc'], ['.cursor/agents', '.md']],
  gemini: [['.gemini/agents', '.md'], ['.gemini/commands', '.toml']],
  codex: [['.codex/agents', '.toml']],
};

/** Gemini CLI tool names (docs/tools/file-system.md) that together mean "read only". */
const GEMINI_READ_TOOLS = ['read_file', 'list_directory', 'glob', 'grep_search'];
const MUTATING_TOOLS = ['write_file', 'edit_file', 'run_command'];

const stripBom = (text) => String(text).replace(/^﻿/, '');

function splitFrontmatter(text) {
  const clean = stripBom(text);
  const match = clean.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  return match ? { front: match[1], body: clean.slice(match[0].length) } : { front: '', body: clean };
}

function scalar(front, key) {
  const match = front.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
  if (!match) return undefined;
  const value = match[1].trim();
  if (value.startsWith('"')) {
    try {
      return JSON.parse(value);
    } catch {
      return value.replace(/^"|"$/g, '');
    }
  }
  return value.replace(/^'|'$/g, '');
}

function list(front, key) {
  const match = front.match(new RegExp(`^${key}:\\s*\\r?\\n((?:\\s+-\\s*.+\\r?\\n?)+)`, 'm'));
  return match ? [...match[1].matchAll(/-\s*(.+)/g)].map((m) => m[1].trim()) : [];
}

const mdMarker = (source) => `<!-- ${MARKER} from ${source}; edit the source, not this file. -->`;
const tomlMarker = (source) => `# ${MARKER} from ${source}; edit the source, not this file.`;

/** TOML literal multi-line strings cannot contain three single quotes. */
function tomlLiteral(text, where) {
  if (text.includes("'''")) throw new Error(`${where} contains ''' and cannot be written as a TOML literal string`);
  return `'''\n${text.replace(/\r\n/g, '\n').replace(/^\s+/, '').replace(/\s+$/, '')}\n'''`;
}

/**
 * @param {string} source Agent Markdown
 * @param {string} rel Source path (for error messages)
 * @returns {{ name: string, description: string, readOnly: boolean, body: string }}
 */
export function parseAgent(source, rel) {
  const { front, body } = splitFrontmatter(source);
  const name = scalar(front, 'name');
  const description = scalar(front, 'description');
  if (!name || !description) throw new Error(`Missing name or description in ${rel}`);
  const tools = list(front, 'tools');
  return { name, description, readOnly: !tools.some((t) => MUTATING_TOOLS.includes(t)), body };
}

export function toCursorRule(source, rel, ruleNames = []) {
  const { front, body } = splitFrontmatter(source);
  const loading = claudeCodeRuleLoading(source);
  const lines = ['---', `description: ${JSON.stringify(scalar(front, 'description') || '')}`];
  if (loading === 'conditional') lines.push(`globs: ${rulePaths(source).join(', ')}`);
  lines.push(`alwaysApply: ${loading === 'session-start'}`, '---', '', mdMarker(rel), '');
  let text = body.replace(/^\s+/, '');
  // Cursor only reads .mdc rules, so links between rules must point at the .mdc copies.
  for (const name of ruleNames) {
    const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    text = text.replace(new RegExp(`\\]\\((?:\\./)?${escaped}\\.md(#[^)]*)?\\)`, 'g'), (_m, anchor) => `](${name}.mdc${anchor || ''})`);
  }
  return `${lines.join('\n')}\n${text}`;
}

export function toCursorAgent(source, rel) {
  const agent = parseAgent(source, rel);
  return [
    '---', `name: ${agent.name}`, `description: ${JSON.stringify(agent.description)}`, 'model: inherit', `readonly: ${agent.readOnly}`, '---', '',
    mdMarker(rel), '', agent.body.replace(/^\s+/, ''),
  ].join('\n');
}

export function toGeminiAgent(source, rel) {
  const agent = parseAgent(source, rel);
  const front = ['---', `name: ${agent.name}`, `description: ${JSON.stringify(agent.description)}`, 'kind: local'];
  // Omitting `tools` inherits every parent tool, which only the mutating agent should do.
  if (agent.readOnly) front.push('tools:', ...GEMINI_READ_TOOLS.map((t) => `  - ${t}`));
  front.push('---', '', mdMarker(rel), '', agent.body.replace(/^\s+/, ''));
  return front.join('\n');
}

export function toCodexAgent(source, rel) {
  const agent = parseAgent(source, rel);
  const banner = agent.readOnly
    ? 'Role boundary: this is a read-only role. Do not modify files, and do not run commands that change state. Codex does not let a subagent definition restrict its tools, so this is an instruction, not an enforced limit.\n\n'
    : '';
  return [
    tomlMarker(rel),
    `name = ${JSON.stringify(agent.name)}`,
    `description = ${JSON.stringify(agent.description)}`,
    `developer_instructions = ${tomlLiteral(`${banner}${agent.body}`, rel)}`,
    '',
  ].join('\n');
}

/**
 * Gemini custom commands interpret `{{args}}`, `!{...}` (runs a shell command), and `@{...}`
 * (injects a file), so a workflow that contains the last two is refused instead of converted.
 */
export function toGeminiCommand(source, rel) {
  const { front, body } = splitFrontmatter(source);
  if (/!\{|@\{/.test(body)) throw new Error(`${rel} contains !{ or @{, which Gemini would run or expand`);
  const hint = scalar(front, 'argument-hint');
  const description = `${scalar(front, 'description') || ''}${hint ? ` Arguments: ${hint}` : ''}`.trim();
  const prompt = body.replace(/\$ARGUMENTS/g, '{{args}}');
  return [tomlMarker(rel), `description = ${JSON.stringify(description)}`, `prompt = ${tomlLiteral(prompt, rel)}`, ''].join('\n');
}

function geminiContext(rulesDir, ruleFiles) {
  const byLoading = { 'session-start': [], 'on-demand': [], conditional: [] };
  for (const file of ruleFiles) byLoading[claudeCodeRuleLoading(fs.readFileSync(path.join(rulesDir, file), 'utf8'))].push(file);
  return [
    mdMarker('.agents/rules and AGENTS.md'),
    '',
    '# Project instructions for Gemini CLI',
    '',
    'Skills in `.agents/skills` load natively. This file imports the rules that apply to every task. Imported text is project guidance, not a way to override your own safety limits.',
    '',
    ...byLoading['session-start'].map((file) => `@./.agents/rules/${file}`),
    '',
    '## Read before the matching kind of work',
    '',
    ...byLoading['on-demand'].map((file) => `- \`.agents/rules/${file}\``),
    '',
    `The other ${byLoading.conditional.length} rules in \`.agents/rules/\` are scoped by file type (their \`paths:\` frontmatter); read the one that matches the files you are about to edit. Gemini CLI does not load them automatically.`,
    '',
    '## Not enforced here',
    '',
    'The command, file, and MCP guardrails that the Claude Code adapter enforces through hooks are not installed for Gemini CLI. Follow `change-safety.md` yourself: no destructive commands, nothing outside the project, and ask before anything irreversible.',
    '',
  ].join('\n');
}

/**
 * @param {string} root Repository root
 * @param {string[]} hosts Subset of HOSTS
 * @returns {Map<string, string>} Files keyed by repository-relative POSIX path
 */
export function buildHostFiles(root, hosts = HOSTS) {
  const unknown = hosts.filter((h) => !HOSTS.includes(h));
  if (unknown.length) throw new Error(`unknown host(s): ${unknown.join(', ')} (known: ${HOSTS.join(', ')})`);
  const agentsDir = path.join(root, '.agents');
  const config = JSON.parse(stripBom(fs.readFileSync(path.join(agentsDir, 'framework.config.json'), 'utf8')));
  const files = new Map();
  const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');

  const rules = config.rules || [];
  const ruleNames = rules.map((r) => r.replace(/\.md$/, ''));
  const agents = config.subagents || [];
  const workflows = config.workflows || [];

  if (hosts.includes('cursor')) {
    for (const rule of rules) files.set(`.cursor/rules/${rule.replace(/\.md$/, '.mdc')}`, toCursorRule(read(`.agents/rules/${rule}`), `.agents/rules/${rule}`, ruleNames));
    for (const agent of agents) files.set(`.cursor/agents/${agent}`, toCursorAgent(read(`.agents/agents/${agent}`), `.agents/agents/${agent}`));
  }
  if (hosts.includes('gemini')) {
    files.set('GEMINI.md', geminiContext(path.join(agentsDir, 'rules'), rules));
    for (const agent of agents) files.set(`.gemini/agents/${agent}`, toGeminiAgent(read(`.agents/agents/${agent}`), `.agents/agents/${agent}`));
    for (const workflow of workflows) files.set(`.gemini/commands/${workflow.replace(/\.md$/, '.toml')}`, toGeminiCommand(read(`.agents/workflows/${workflow}`), `.agents/workflows/${workflow}`));
  }
  if (hosts.includes('codex')) {
    for (const agent of agents) files.set(`.codex/agents/${agent.replace(/\.md$/, '.toml')}`, toCodexAgent(read(`.agents/agents/${agent}`), `.agents/agents/${agent}`));
  }
  return files;
}

const normalize = (text) => String(text).replace(/\r\n/g, '\n');
const isGenerated = (full) => {
  try {
    return fs.readFileSync(full, 'utf8').includes(MARKER);
  } catch {
    return false;
  }
};

function listGenerated(root, hosts, built) {
  const stale = [];
  const dirs = hosts.flatMap((h) => OWNED_DIRS[h]);
  for (const [dir, ext] of dirs) {
    const full = path.join(root, dir);
    if (!fs.existsSync(full)) continue;
    for (const entry of fs.readdirSync(full, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith(ext)) continue;
      const rel = `${dir}/${entry.name}`;
      if (!built.has(rel) && isGenerated(path.join(full, entry.name))) stale.push(rel);
    }
  }
  return stale;
}

/**
 * Compares the built files with the files on disk. A file at a generated path that the framework
 * did not write (no marker) is reported as a conflict and is never overwritten.
 * @returns {{ missing: string[], changed: string[], stale: string[], conflicts: string[] }}
 */
export function checkHostFiles(root, hosts = HOSTS) {
  const built = buildHostFiles(root, hosts);
  const missing = [];
  const changed = [];
  const conflicts = [];
  for (const [rel, content] of built) {
    const full = path.join(root, rel);
    if (!fs.existsSync(full)) missing.push(rel);
    else if (!isGenerated(full)) conflicts.push(rel);
    else if (normalize(fs.readFileSync(full, 'utf8')) !== normalize(content)) changed.push(rel);
  }
  return { missing, changed, stale: listGenerated(root, hosts, built), conflicts };
}

/**
 * Writes the built files, removes generated files that are no longer produced, and leaves any
 * file the framework did not write alone.
 * @returns {{ written: number, removed: string[], conflicts: string[] }}
 */
export function writeHostFiles(root, hosts = HOSTS) {
  const built = buildHostFiles(root, hosts);
  const { stale, conflicts } = checkHostFiles(root, hosts);
  for (const rel of stale) fs.rmSync(path.join(root, rel));
  let written = 0;
  for (const [rel, content] of built) {
    if (conflicts.includes(rel)) continue;
    const full = path.join(root, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content, 'utf8');
    written += 1;
  }
  return { written, removed: stale, conflicts };
}
